// Twenty blind answers are the scarcest thing this page collects - they cost a person real
// attention and cannot be regenerated by any model. Losing them to a reload is the worst thing
// the page could do, so the work in progress is kept in this browser's storage. Only what was
// typed, fetched or answered is kept; the decoded circuit is rebuilt from its bytes. Storage
// can be missing or full (private windows, quotas), and then the page simply forgets, as before.
const SAVED = "gatecraft.decide.v1";
const KEPT = ["sentence", "widened", "specText", "spec", "read", "fill", "fillStats", "filledBy", "frozen", "sheet", "at", "calibration", "codes"];

function restore() {
  try {
    const saved = JSON.parse(localStorage.getItem(SAVED) ?? "null");
    if (saved && typeof saved === "object") for (const key of KEPT) if (key in saved) decideState[key] = saved[key];
  } catch { /* nothing kept, or unreadable: start fresh */ }
}

function persist() {
  try { localStorage.setItem(SAVED, JSON.stringify(Object.fromEntries(KEPT.map((k) => [k, decideState[k] ?? null])))); }
  catch { /* storage full or refused: this visit still works, it just will not survive a reload */ }
}

export function forgetDecision() {
  for (const key of KEPT) decideState[key] = key === "specText" ? "" : key === "at" ? 0 : null;
  decideState.error = "";
  try { localStorage.removeItem(SAVED); } catch { /* nothing to remove */ }
}

restore();

