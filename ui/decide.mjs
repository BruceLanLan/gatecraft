function renderFill(root, t, redraw) {
  const section = card(t("decFillTitle"), 2);
  const site = decideState.hosted;
  section.append(el("p", "hint", t(site ? "decFillHintSite" : "decFillHint")));
  // Without a key: a free fill if any are left, and always the ways to not need one.
  const freeLeft = decideState.keyPresent === false && decideState.trial?.available ? decideState.trial.left : 0;
  if (decideState.keyPresent === false) section.append(el("p", freeLeft > 0 ? "hint" : "warn", freeLeft > 0 ? t(site ? "decTrialOfferSite" : "decTrialOffer", freeLeft, decideState.trial.limit) : decideState.trial?.available ? t(site ? "decTrialGoneSite" : "decTrialGone", decideState.trial.limit) : t(site ? "decNoKeySite" : "decNoKey")));

  // Two sources, because a page that can do nothing without a key is a page most visitors
  // bounce off. Asking the model is the real thing; filling from a rule the file already
  // states asks nobody, needs no key, and still carries the whole rest of the flow - freeze,
  // proof, poke it, twenty questions. It is also honest about what it is: a decision you could
  // already write as a rule is one the calibration at the end ought to refuse.
  const fillWith = async (rule) => {
    decideState.busy = "fill"; decideState.error = ""; renderDecide(root, t);
    try {
      const out = await api("decision.fill", { spec: decideState.spec, ...(rule ? { rule } : {}) });
      // Nothing answered is not a fill to freeze: say what the model said instead of carrying an
      // empty table into the proof and failing three steps later with something opaque.
      if (!out.answered) throw new Error(t("decNothingAnswered", out.fill.rows.find((r) => r?.error)?.error ?? ""));
      decideState.fillStats = out;
      if (out.trial && decideState.trial) decideState.trial.left = out.trial.left;
      await probeKey();
      decideState.filledBy = rule ? "rule" : "model";
      await freezeAndDraw(out.fill);
    } catch (error) { decideState.error = String(error.message); }
    decideState.busy = ""; redraw();
  };

  // The person's own model, asked from this page. A chat model's self-reported confidence was
  // measured to carry nothing, so each situation is asked ASKS times and the confidence is how
  // often the answers agreed: at three asks and the usual 0.7 threshold, only a unanimous row
  // is acted on, and those were measured to reproduce 96-98% of the time. Nothing here goes
  // through this server: the prompt goes from the browser to the provider, with the key that
  // is already in this page for drafting.
  const legal = decideState.read?.legal ?? 0;
  const m = modelAccess.get();
  const calls = legal * ASKS;
  const fillOwn = async () => {
    decideState.busy = "own"; decideState.error = ""; decideState.progress = { done: 0, total: legal }; renderDecide(root, t);
    try {
      const d = parseDecision(decideState.spec);
      const ask = async (prompt) => {
        const { url, init } = modelRequest({ ...m, messages: [{ role: "user", content: prompt }] });
        let response;
        try { response = await fetch(url, { ...init, signal: AbortSignal.timeout(120_000) }); }
        catch (error) { throw new Error(localBlocked(url) ? t("decLocalBlocked") : t("decDraftUnreachable", new URL(url).origin, error.name === "TimeoutError" ? "timed out" : error.message)); }
        let body = null;
        try { body = await response.json(); } catch { /* the status says enough */ }
        return replyText(m.provider, response.status, body);
      };
      const one = textFiller(d, { ask, source: "chat", model: m.label });
      const local = /^http:\/\/(127\.0\.0\.1|localhost)/.test(String(m.baseUrl ?? ""));
      let shown = 0;
      const fill = await fillDecision(d, majorityFiller(one, ASKS), {
        asksPerRow: ASKS,
        concurrency: local ? 2 : 6,
        onRow: () => {
          decideState.progress.done += 1;
          // Redraw at most every few rows; a full redraw per answer would thrash the page.
          if (decideState.progress.done - shown >= Math.max(1, Math.floor(legal / 40)) || decideState.progress.done === legal) { shown = decideState.progress.done; renderDecide(root, t); }
        },
      });
      const rows = fill.rows.filter(Boolean);
      const answered = rows.filter((r) => r.choice);
      decideState.fillStats = { answered: answered.length, legal, failed: rows.filter((r) => r.source === "failed").length, settled: answered.filter((r) => (r.confidence ?? 0) >= d.threshold).length };
      decideState.filledBy = "own";
      if (!answered.length) throw new Error(t("decOwnNothing", rows.find((r) => r.error)?.error ?? ""));
      await freezeAndDraw(fill);
    } catch (error) { decideState.error = String(error.message); }
    decideState.busy = ""; decideState.progress = null; redraw();
  };

  const bar = el("div", "row");
  const go = el("button", "primary", decideState.busy === "fill" ? t("decFilling") : t("decFill"));
  go.disabled = Boolean(decideState.busy) || (decideState.keyPresent === false && freeLeft <= 0);
  if (decideState.keyPresent === false && freeLeft > 0 && decideState.busy !== "fill") go.textContent = t("decFillTrial", freeLeft);
  go.addEventListener("click", () => fillWith(null));
  bar.append(go);
  const own = el("button", decideState.keyPresent === false ? "primary" : "ghost", decideState.busy === "own" && decideState.progress ? t("decOwnProgress", decideState.progress.done, decideState.progress.total) : t("decFillOwn", calls));
  own.disabled = Boolean(decideState.busy) || !m?.ready || legal > OWN_MAX;
  own.addEventListener("click", fillOwn);
  bar.append(own);
  const rule = typeof decideState.spec?.rule === "string" ? decideState.spec.rule : null;
  if (rule) {
    const byRule = el("button", "ghost", t("decFillByRule"));
    byRule.disabled = Boolean(decideState.busy);
    byRule.addEventListener("click", () => fillWith(rule));
    bar.append(byRule);
  }
  section.append(bar);
  section.append(el("p", "hint", !m?.ready ? t("decOwnNoModel") : legal > OWN_MAX ? t("decOwnTooMany", legal, OWN_MAX) : t("decOwnHint", m.label, calls)));
  // The fill buttons come first; where a key comes from sits under them.
  section.append(renderJevKey(t, redraw));

  if (decideState.fillStats) {
    const s = decideState.fillStats;
    section.append(el("p", "result", decideState.filledBy === "rule" ? t("decFilledRule", s.answered, s.legal) : t("decFilled", s.answered, s.settled, s.legal)));
    section.append(el("p", "hint", decideState.filledBy === "rule" ? t("decFilledByRule") : decideState.filledBy === "own" ? t("decFilledByOwn", ASKS) : t("decFilledByModel")));
    if (decideState.fillStats.trial) section.append(el("p", "warn", t("decTrialUsed", decideState.fillStats.trial.left, decideState.fillStats.trial.limit)));
  }
  if (decideState.frozen) {
    const c = decideState.frozen.certificate;
    section.append(el("p", "result", t("decFrozen", c.circuit.nand, c.verification.rowsChecked, decideState.frozen.review.length)));
    section.append(el("p", "warn", t("decProofNotPolicy")));
    section.append(renderTry(t, redraw));
  }
  return section;
}

// Asks per situation when the person's own chat model fills the table, and how many situations
// that is allowed for from a browser tab: 512 situations is already 1,536 calls on their bill.
const ASKS = 3;
const OWN_MAX = 512;

// Poke the thing that was just built.
//
// The gallery lets you press the buttons on a circuit the moment it compiles, and that is the
// part of this page people actually play with. A decision had no equivalent: you got a gate
// count and a row count and nothing to touch. This runs THE NETLIST - decoded and simulated
// here in the page, the same bytes the certificate is about - so what you poke is the thing
// that would ship, not a preview of it. Clicking a code with no phrase is worth doing at least
// once: the answer falls to safe with review set, and no model, table or judgement is involved.
function circuitOf() {
  const net = decideState.frozen?.netlist;
  if (!net) return null;
  if (decideState.circuitFor !== net.netlistHex) {
    decideState.circuit = decodeCircuit(hexToBytes(net.netlistHex), net.nIn, net.nOut);
    decideState.circuitFor = net.netlistHex;
  }
  return decideState.circuit;
}

function renderTry(t, redraw) {
  const book = decideState.frozen.codebook;
  const net = decideState.frozen.netlist;
  const box = el("div", "tryit");
  box.append(el("h3", "tryit-title", t("decTryTitle")));
  box.append(el("p", "hint", t("decTryHint")));

  decideState.codes ??= {};
  let row = 0, shift = 0, illegalField = null;
  for (const f of book.observe) {
    const legal = Object.keys(f.values).map(Number).sort((a, b) => a - b);
    if (decideState.codes[f.field] === undefined) decideState.codes[f.field] = legal[0];
    const chosen = decideState.codes[f.field];
    if (!legal.includes(chosen) && illegalField === null) illegalField = f.field;
    row |= chosen << shift;
    shift += f.width;

    const line = el("div", "try-line");
    line.append(el("span", "sit-field", f.field));
    const picks = el("div", "try-picks");
    for (let code = 0; code < 2 ** f.width; code++) {
      const known = legal.includes(code);
      const button = el("button", `try-code${chosen === code ? " on" : ""}${known ? "" : " unknown"}`,
        known ? f.values[code] : t("decTryNoPhrase", code));
      button.addEventListener("click", () => { decideState.codes[f.field] = code; redraw(); });
      picks.append(button);
    }
    line.append(picks);
    box.append(line);
  }

  const out = simulate(circuitOf(), Array.from({ length: net.nIn }, (_, i) => (row >>> i) & 1), new Uint8Array(0));
  let code = 0;
  for (let b = 0; b < book.act.bits; b++) code |= (out.outputs[b] ? 1 : 0) << b;
  const review = Boolean(out.outputs[book.act.bits]);
  const choice = book.act.choices[code] ?? book.act.choices.find((c) => c.choice === book.act.safe);

  const answer = el("div", `try-answer${review ? " reviewing" : ""}`);
  answer.append(el("span", "try-label", t("decTryAnswer")));
  answer.append(el("strong", "try-choice", choice.phrase));
  answer.append(el("span", "try-name mono", choice.choice));
  answer.append(el("span", "try-flag", review ? t("decTryReview") : t("decTryActs")));
  box.append(answer);
  if (illegalField) box.append(el("p", "warn", t("decTryIllegalRow", illegalField)));

  // The circuit itself, lit by the situation picked above. This is the part the rest of
  // gatecraft has always shown and the decision view did not: the thing that was proven is a
  // few dozen NAND gates, and you can watch every one of them decide.
  const layout = drawCircuit ? diagramLayout(circuitOf()) : null;
  if (layout) {
    const names = decisionPinNames(parseDecision(decideState.spec));
    const wrap = el("div", "try-circuit");
    const head = el("div", "try-circuit-head");
    head.append(el("span", "try-label", t("decCircuitTitle", net.nand ?? circuitOf().elements.length)), el("span", "hint", t("decCircuitLit")));
    wrap.append(head, drawCircuit(layout, out.signals, { names }));
    box.append(wrap);
  } else if (drawCircuit) {
    box.append(el("p", "hint", t("decCircuitTooBig")));
  }
  return box;
}

// What to do with the file: the three lines of code, written with this decision's own field
// names and codes, and the same thing as words to hand a coding agent - because the step people
// get wrong is turning their program's data into the codes, and that is theirs to write.
function useItText(spec, name) {
  const fields = Object.entries(spec.observe);
  const choices = Object.keys(spec.act.choices);
  const codeLines = fields.map(([f, v]) => `//   ${f}: ${Object.entries(v.values).map(([c, p]) => `${c} = ${p}`).join(" · ")}`);
  const code = [
    `import { decide } from "./${name}";`,
    "",
    "// Your program turns what it already knows into these codes:",
    ...codeLines,
    `const { action, review } = decide({ ${fields.map(([f]) => f).join(", ")} });`,
    "",
    `if (review) handToAPerson();   // a code with no meaning, or a case it was not sure of`,
    `else ${choices.length === 2 ? `if (action === "${choices[0]}") { /* ${spec.act.choices[choices[0]]} */ } else { /* ${spec.act.choices[choices[1]]} */ }` : `act(action);          // one of: ${choices.join(" | ")}`}`,
  ].join("\n");
  const agent = [
    `Add ${name} to this project. It is a frozen, proven decision: "${spec.question}"`,
    "It exports decide(codes), which returns { action, review }.",
    "Write one small function that turns our own data into these codes, exactly as described:",
    ...fields.map(([f, v]) => `- ${f} (${v.raw ?? "see the codebook"}): ${Object.entries(v.values).map(([c, p]) => `${c} = ${p}`).join("; ")}`),
    `Then replace the place where we currently decide this (for example a call to a language model) with decide(). When review is true, hand the case to a person instead of acting. The possible actions are: ${choices.map((c) => `${c} (${spec.act.choices[c]})`).join(", ")}.`,
    "Do not change the module itself; write tests for the bucketing function.",
  ].join("\n");
  return { code, agent };
}

function renderUseIt(t) {
  const name = decideState.exported ?? `${decideState.spec.name}.decision.mjs`;
  const { code, agent } = useItText(decideState.spec, name);
  const box = el("div", "useit");
  box.append(el("h3", "useit-title", t("useItTitle")));
  box.append(el("pre", "mono useit-code", code));
  box.append(el("p", "hint", t("useItAgent")));
  const words = el("pre", "useit-agent", agent);
  const copy = el("button", "ghost", t("useItCopy"));
  copy.addEventListener("click", async () => {
    try { await navigator.clipboard.writeText(agent); copy.textContent = t("useItCopied"); }
    catch { const r = document.createRange(); r.selectNodeContents(words); const sel = getSelection(); sel.removeAllRanges(); sel.addRange(r); }
  });
  box.append(words, copy);
  return box;
}

// Step 3: the gate. One situation at a time, and never what the model said about it.
function renderAsk(root, t, redraw) {
  const section = card(t("decAskTitle"), 3);
  section.append(el("p", "hint", t("decAskHint")));
  const sheet = decideState.sheet;
  if (!sheet) return section;

  const answered = sheet.anchors.filter((a) => a.choice || a.allow?.length).length;
  const question = sheet.anchors[decideState.at];
  section.append(el("p", "count", t("decAskCount", answered, sheet.anchors.length)));

  if (question) {
    const box = el("div", "situation");
    for (const [field, phrase] of Object.entries(question.situation)) {
      const line = el("div", "sit-line");
      line.append(el("span", "sit-field", field), el("span", "sit-phrase", phrase));
      box.append(line);
    }
    section.append(box);
    section.append(el("p", "ask-question", decideState.read?.text ? decideState.spec.question : ""));

    const choices = el("div", "choices");
    const picked = new Set(question.allow ?? (question.choice ? [question.choice] : []));
    for (const [name, phrase] of Object.entries(decideState.spec.act.choices)) {
      const button = el("button", picked.has(name) ? "choice on" : "choice");
      button.append(el("strong", null, name), el("span", null, phrase));
      button.addEventListener("click", () => {
        const next = new Set(picked);
        next.has(name) ? next.delete(name) : next.add(name);
        if (next.size === 0) { delete question.choice; delete question.allow; }
        else if (next.size === 1) { question.choice = [...next][0]; delete question.allow; }
        else { question.allow = [...next]; delete question.choice; }
        redraw();
      });
      choices.append(button);
    }
    section.append(choices);
    section.append(el("p", "hint", t("decAskMulti")));
    section.append(el("p", "hint keys", t("decAskKeys")));
  }

  const nav = el("div", "row");
  const back = el("button", "ghost", t("decBack"));
  back.disabled = decideState.at === 0;
  back.addEventListener("click", () => { decideState.at -= 1; redraw(); });
  const skip = el("button", "ghost", t("decSkip"));
  skip.addEventListener("click", () => { decideState.at = Math.min(decideState.at + 1, sheet.anchors.length - 1); redraw(); });
  const next = el("button", "primary", t("decNext"));
  next.disabled = decideState.at >= sheet.anchors.length - 1;
  next.addEventListener("click", () => { decideState.at += 1; redraw(); });
  nav.append(back, skip, next);
  section.append(nav);
  return section;
}

// Step 4: can this decision be delegated at all, and with the threshold where.
function renderVerdict(root, t, redraw) {
  const section = card(t("decVerdictTitle"), 4);
  const sheet = decideState.sheet;
  const answered = sheet ? sheet.anchors.filter((a) => a.choice || a.allow?.length).length : 0;
  section.append(el("p", "hint", t("decVerdictHint")));

  const bar = el("div", "row");
  const go = el("button", "primary", t("decCalibrate"));
  go.disabled = !sheet || answered < 5 || Boolean(decideState.busy);
  go.addEventListener("click", async () => {
    decideState.busy = "cal"; decideState.error = ""; redraw();
    try {
      decideState.calibration = await api("decision.calibrate", { spec: decideState.spec, fill: decideState.fill, anchors: decideState.sheet, rule: decideState.spec.rule ?? null });
    } catch (error) { decideState.error = String(error.message); }
    decideState.busy = ""; redraw();
  });
  bar.append(go);
  if (sheet && answered < 5) bar.append(el("span", "hint", t("decNeedFive", answered)));
  section.append(bar);

  const cal = decideState.calibration;
  if (cal) {
    // A fill with one certainty in it makes seven identical rungs. Drawing all seven would
    // offer a choice that is not there, so it collapses to the single row it really is.
    const flat = (cal.confidenceValues ?? 2) <= 1;
    const table = el("table", "sweep");
    const head = el("tr");
    for (const key of ["decThreshold", "decDecides", "decAnchorsAbove", "decAgree"]) head.append(el("th", null, t(key)));
    table.append(head);
    for (const rung of (flat ? cal.sweep.slice(0, 1) : cal.sweep)) {
      const tr = el("tr", rung.threshold === cal.calibratedThreshold ? "chosen" : null);
      tr.append(el("td", "mono", flat ? t("decAnyThreshold") : String(rung.threshold)));
      tr.append(el("td", null, `${rung.settled}/${cal.legal} = ${Math.round(100 * rung.settledShare)}%`));
      tr.append(el("td", null, String(rung.anchorsAbove)));
      tr.append(el("td", rung.clean ? "clean" : null, `${rung.held}/${rung.anchorsAbove}`));
      table.append(tr);
    }
    section.append(table);
    if (flat) section.append(el("p", "hint", t("decOneConfidence")));

    // "Too few" is still a refusal - nothing is exported on it - but it is not an accusation, and
    // the way out is to answer more, not to give up on the decision.
    const tooFew = cal.verdict === "do-not-delegate" && cal.why === "too-few";
    const verdict = el("div", `verdict ${tooFew ? "too-few" : cal.verdict}`);
    verdict.append(el("strong", null, tooFew ? t("decV_too_few") : t(`decV_${cal.verdict.replace(/-/g, "_")}`)));
    verdict.append(el("p", null, tooFew
      ? (cal.agreesUpTo ? t("decVtooFewWhy", cal.agreesUpTo.held, cal.agreesUpTo.anchorsAbove, cal.agreesUpTo.threshold, cal.least) : t("decVtooFewNone", cal.least))
      : cal.verdict === "do-not-delegate"
      ? (flat ? t("decVdontWhyFlat", cal.sweep[0].anchorsAbove - cal.sweep[0].held, cal.sweep[0].anchorsAbove) : t("decVdontWhy"))
      : cal.verdict === "write-the-rule-instead"
        ? t("decVruleWhy", Math.round(100 * (cal.rule?.share ?? 0)))
        : t("decVdoWhy", cal.calibratedThreshold, Math.round(100 * (cal.decides ?? 0)))));
    section.append(verdict);

    if (cal.verdict !== "do-not-delegate") {
      const download = el("button", "primary", t("decExport"));
      download.addEventListener("click", async () => {
        try {
          const out = await api("decision.export", { spec: decideState.spec, fill: decideState.fill, anchors: decideState.sheet, calibration: cal });
          const url = URL.createObjectURL(new Blob([out.text], { type: "text/javascript" }));
          const a = document.createElement("a");
          a.href = url; a.download = out.name; a.click();
          URL.revokeObjectURL(url);
          decideState.exported = out.name;
          redraw();
        } catch (error) { decideState.error = String(error.message); redraw(); }
      });
      section.append(download);
      section.append(el("p", "hint", t("decExportHint")));
      section.append(renderUseIt(t));
    } else {
      section.append(el("p", "warn", tooFew ? t("decNoExportYet") : t("decNoExport")));
    }
  }
  return section;
}

// Twenty questions by mouse is forty clicks. A digit picks that option and moves on, which is
// how people actually get through a survey; shift+digit adds a second defensible option without
// moving, arrows walk back and forth. Typing in the codebook box is never intercepted.
let keyTarget = null;
function onKey(event) {
  if (!keyTarget || event.metaKey || event.ctrlKey || event.altKey) return;
  const { root, t } = keyTarget;
  if (root.hidden || !decideState.sheet || !decideState.spec) return;
  if (/^(INPUT|TEXTAREA|SELECT)$/.test(event.target?.tagName ?? "") || event.target?.isContentEditable) return;
  const anchors = decideState.sheet.anchors;
  const question = anchors[decideState.at];
  const names = Object.keys(decideState.spec.act.choices);
  const digit = /^Digit([1-9])$/.exec(event.code);
  if (digit && question && Number(digit[1]) <= names.length) {
    const name = names[Number(digit[1]) - 1];
    if (event.shiftKey) {
      const set = new Set(question.allow ?? (question.choice ? [question.choice] : []));
      set.has(name) ? set.delete(name) : set.add(name);
      delete question.choice; delete question.allow;
      if (set.size === 1) question.choice = [...set][0];
      else if (set.size > 1) question.allow = [...set];
    } else {
      question.choice = name;
      delete question.allow;
      decideState.at = Math.min(decideState.at + 1, anchors.length - 1);
    }
  } else if (event.key === "ArrowRight") decideState.at = Math.min(decideState.at + 1, anchors.length - 1);
  else if (event.key === "ArrowLeft") decideState.at = Math.max(decideState.at - 1, 0);
  else return;
  event.preventDefault();
  renderDecide(root, t);
}

export function renderDecide(root, t) {
  root.replaceChildren();
  const redraw = () => renderDecide(root, t);
  if (!keyTarget) {
    document.addEventListener("keydown", onKey);
    // Someone who went to a terminal to save the key comes back to this tab; notice it then.
    window.addEventListener("focus", () => { if (keyTarget && !keyTarget.root.hidden) probeKey().then(redrawDecide, () => {}); });
  }
  keyTarget = { root, t };
  persist();
  if (decideState.read) {
    const bar = el("div", "row restart");
    const again = el("button", "ghost", t("decStartOver"));
    again.addEventListener("click", () => { forgetDecision(); redraw(); });
    bar.append(el("span", "hint", t("decKept")), again);
    root.append(bar);
  }
  if (!decideState.read) root.append(renderLanding(t, { draw: drawCircuit, onTour: () => tourFor(t).start(), onOwn: startOwn }));
  root.append(renderSpec(root, t, () => renderDecide(root, t)));
  if (decideState.read) root.append(renderFill(root, t, () => renderDecide(root, t)));
  if (decideState.sheet) root.append(renderAsk(root, t, () => renderDecide(root, t)));
  if (decideState.sheet) root.append(renderVerdict(root, t, () => renderDecide(root, t)));
  if (decideState.error) root.append(el("p", "warn", decideState.error));
  tour?.refocus();
}

export async function probeKey() {
  try {
    decideState.hosted = !(await hasServer());
    const health = await api("health.status");
    decideState.keyPresent = health.decisionKey === "present";
    // No key of their own: ask how many of the free fills this address has left, so the page
    // can offer one instead of a dead button.
    decideState.trial = decideState.keyPresent ? null : await api("decision.trial").catch(() => null);
  } catch { decideState.keyPresent = null; }
}
