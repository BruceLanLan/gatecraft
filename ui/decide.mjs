async function readBackNow() {
  decideState.error = "";
  try {
    // Pure JSON, or a whole reply pasted from an AI chat with prose and fences around it. Widths
    // too small for their own codes are settled the same way a drafted file's are.
    let spec;
    try { spec = JSON.parse(decideState.specText); }
    catch {
      const settled = settleWidths(specFromReply(decideState.specText));
      spec = settled.spec;
      decideState.widened = settled.fixed;
      decideState.specText = JSON.stringify(spec, null, 2);
    }
    decideState.read = await api("decision.review", { spec });
    decideState.spec = spec;
    decideState.fill = decideState.frozen = decideState.sheet = decideState.calibration = null;
    decideState.codes = {};
  } catch (error) { decideState.error = String(error.message); decideState.read = null; }
}

// One sentence in, a codebook out, and straight into the read-back - because the draft is the
// model's guess and the read-back's notes (the wall, the safe action) are where a person checks
// it. Nobody should be handed a drafted codebook without that step in front of them.
function renderDraft(t, redraw) {
  const box = el("div", "draft");
  box.append(el("p", "hint", t("decDraftOr")));
  const line = el("textarea", "draft-input");
  line.rows = 2;
  line.placeholder = t("decDraftPlaceholder");
  line.value = decideState.sentence ?? "";
  line.addEventListener("input", () => { decideState.sentence = line.value; });
  box.append(line);

  const m = modelAccess.get();
  const bar = el("div", "row");
  const go = el("button", "primary", decideState.busy === "draft" ? t("decDrafting") : t("decDraftGo"));
  go.disabled = Boolean(decideState.busy) || !m?.ready;
  go.addEventListener("click", async () => {
    const sentence = (decideState.sentence ?? "").trim();
    if (!sentence) { decideState.error = t("decDraftEmpty"); redraw(); return; }
    decideState.busy = "draft"; decideState.error = ""; redraw();
    try {
      const { spec, fixed } = await draftCodebook(sentence, t);
      decideState.specText = JSON.stringify(spec, null, 2);
      await readBackNow();
      decideState.widened = fixed;
    } catch (error) { decideState.error = String(error.message); }
    decideState.busy = ""; redraw();
  });
  const pick = el("button", "ghost", t("decDraftPick"));
  pick.addEventListener("click", () => modelAccess.open());
  // No model set up at all: the same prompt, for any AI chat the visitor already uses. They paste
  // the whole reply into the box below; the read-back finds the JSON in it.
  const copy = el("button", "ghost", decideState.copied ? t("decDraftCopied") : t("decDraftCopy"));
  copy.addEventListener("click", async () => {
    const sentence = (decideState.sentence ?? "").trim();
    if (!sentence) { decideState.error = t("decDraftEmpty"); redraw(); return; }
    const prompt = codebookPrompt(sentence);
    try { await navigator.clipboard.writeText(prompt); decideState.copied = true; decideState.promptShown = null; }
    catch { decideState.copied = false; decideState.promptShown = prompt; }
    decideState.error = "";
    redraw();
  });
  bar.append(go, copy, pick);
  box.append(bar);
  box.append(el("p", "hint", m?.ready ? t("decDraftModel", m.label) : t("decDraftNoModel")));
  if (decideState.copied) box.append(el("p", "result", t("decDraftPasteBack")));
  if (decideState.promptShown) {
    const shown = el("textarea", "draft-prompt mono");
    shown.rows = 6; shown.readOnly = true; shown.value = decideState.promptShown;
    box.append(el("p", "hint", t("decDraftSelect")), shown);
  }
  return box;
}

// Step 1: the codebook, and the read-back that makes a person look at the buckets.
function renderSpec(root, t, redraw) {
  const section = card(t("decSpecTitle"), 1);
  section.append(el("p", "hint", t("decSpecHint")));

  // Nobody writes one of these from a blank box. These two are real decisions from this repo,
  // both already carried through anchors, so the first run shows the whole flow rather than a
  // parse error.
  const picks = el("div", "row examples");
  picks.append(el("span", "hint", t("decExamples")));
  for (const [name, key] of EXAMPLES) {
    const button = el("button", "ghost", t(key));
    button.addEventListener("click", async () => {
      try {
        const spec = await (await fetch(new URL(`../examples/${name}.decision.json`, import.meta.url))).json();
        decideState.specText = JSON.stringify(spec, null, 2);
        decideState.read = decideState.fill = decideState.frozen = decideState.sheet = decideState.calibration = null;
        decideState.error = "";
      } catch { decideState.error = t("decExFailed"); }
      redraw();
    });
    picks.append(button);
  }
  section.append(picks);
  section.append(renderDraft(t, redraw));
  const area = el("textarea", "spec-input");
  area.rows = 8;
  area.placeholder = t("decSpecPlaceholder");
  area.value = decideState.specText;
  area.addEventListener("input", () => { decideState.specText = area.value; });
  section.append(area);

  const bar = el("div", "row");
  const read = el("button", "primary", t("decRead"));
  read.addEventListener("click", async () => { decideState.widened = null; await readBackNow(); redraw(); });
  bar.append(read);
  section.append(bar);

  if (decideState.read) {
    // The codebook itself belongs in monospace - it is a table of codes. What does not is the
    // part that is advice: the buckets that look like they live on the far side of the wall,
    // and the safe action, which is the field a model gets wrong in the way that matters. Those
    // were scrolling past inside the blob; they come out above it.
    const notes = [...(decideState.read.notes ?? [])];
    for (const w of decideState.widened ?? []) notes.unshift({ about: w.field, kind: "width", says: t("decWidened", w.field, w.from, w.to) });
    if (notes.length) {
      const list = el("div", "readnotes");
      list.append(el("p", "hint", t("decNotesTitle", notes.length)));
      for (const note of notes) {
        const item = el("div", `readnote${note.kind === "safe" ? " safe" : ""}`);
        item.append(el("span", "note-about mono", note.about));
        item.append(el("span", null, note.says));
        list.append(item);
      }
      section.append(list);
    }
    section.append(el("pre", "readback mono", decideState.read.text));
  }
  return section;
}

